#!/usr/bin/env python3
"""Tests for check_commit_trailers.py. Run: python3 scripts/test_check_commit_trailers.py"""
import unittest

from check_commit_trailers import check, offending_lines


class Trailers(unittest.TestCase):
    def test_clean_messages_pass(self):
        self.assertEqual(check([{"sha": "a" * 40, "message": "fix: a thing\n\nBody text."}]), [])
        self.assertEqual(
            check([{"sha": "a" * 40, "message": "feat: x\n\nCo-authored-by: Sam Lee <sam@example.com>"}]),
            [],
        )

    def test_ai_co_author_trailers_fail(self):
        for name in (
            "Claude Sonnet 5.5 <noreply@anthropic.com>",
            "Claude <noreply@anthropic.com>",
            "GitHub Copilot <copilot@github.com>",
            "Codex <codex@openai.com>",
            "Gemini <gemini@google.com>",
        ):
            for key in ("Co-Authored-By", "Co-authored-by", "co-authored-by"):
                self.assertTrue(offending_lines(f"fix: x\n\n{key}: {name}"), (key, name))

    def test_generated_with_lines_fail(self):
        self.assertTrue(offending_lines("fix: x\n\n\U0001F916 Generated with Claude Code"))
        self.assertTrue(offending_lines("fix: x\n\nGenerated by an assistant"))

    def test_a_word_in_prose_is_fine(self):
        self.assertEqual(offending_lines("fix: stop generating with stale keys\n\nUses Claude's name in docs."), [])

    def test_reports_the_short_sha_and_line(self):
        problems = check([{"sha": "abcdef1234", "message": "x\n\nCo-Authored-By: Claude <noreply@anthropic.com>"}])
        self.assertEqual(problems, [("abcdef1", "Co-Authored-By: Claude <noreply@anthropic.com>")])


if __name__ == "__main__":
    unittest.main()
